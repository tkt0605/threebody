// Markdown記法を「声で読み上げる／スクリーンリーダーが読む」ためのプレーンテキストにする。
// TTS（useTTS）とライブリージョン（ChatLiveRegion）の両方が同じ変換を必要とするため、
// どちらのcomposableにも属さない純関数としてここに置く
export function stripMarkdown(text: string): string {
  return text
    .replace(/```[\s\S]*?```/g, '')          // コードブロック（フェンスは中身ごと丸ごと落とす）
    // インラインコードは中身を残し、バッククォートだけ外す。中身ごと落とすと
    // `ws` や `escapeHtml` のような普通の技術用語まで欠落し、文が不自然になっていた
    // （CLIコマンドの読み上げを避けたいなら、フェンス（```bash ... ```）で書かせる方で対処する）
    .replace(/`([^`]+)`/g, '$1')             // インラインコード
    .replace(/!\[([^\]]*)\]\([^)]*\)/g, '$1') // 画像
    .replace(/\[([^\]]*)\]\([^)]*\)/g, '$1')  // リンク（半角括弧を消費するため、下の括弧除去より先に置く）
    .replace(/\s*（[^（）]*）/g, '')            // 括弧の中身（全角）は読み上げない
    .replace(/\s*\([^()]*\)/g, '')            // 括弧の中身（半角）は読み上げない。前の空白ごと消し、二重スペースを残さない
    .replace(/^#{1,6}\s+/gm, '')             // 見出し
    .replace(/\*\*([^*]+)\*\*/g, '$1')       // 太字(**)
    .replace(/__([^_]+)__/g, '$1')           // 太字(__)
    .replace(/\*([^*]+)\*/g, '$1')           // 斜体(*)
    .replace(/_([^_]+)_/g, '$1')             // 斜体(_)
    .replace(/^\s*[-*+]\s+/gm, '')           // 箇条書き記号
    .replace(/^\s*\d+\.\s+/gm, '')           // 番号付きリスト記号
    .replace(/^>\s+/gm, '')                  // 引用
    .trim()
}

// プロンプトの層。ThreeBody は他社モデルを借りて動くため、大手が持つ「訓練で焼き込む層」を
// 持てない。その負担がプロンプトに来るので、置き場所を決めておかないと同じ規則が
// 主体・副体・経路ごとに写し取られ、片方だけ古くなる（実測: 「コードを書くな」が
// 共有キー経路にだけ届いていなかった）。
//
//   層1 CORE_PRINCIPLES  — 主体・副体を問わず、全ての体に必ず入る規範。
//   層2 PRIMARY_CONTRACT / buildSynthesisLayer / secondaryPrompt.ts の役割定義
//                        — 役割ごとの契約。層1と重ねて初めて完成する。
//
// 【層1に入れてよいものの基準】
// 主体にも副体にも同じ形で当てはまること。片方にしか当てはまらないものは層2へ置く。
// 「答え方」は副体に当てはまらない（副体は答えを書かない）ので層2。
// 「言語」も層1に見えるが入れない。主体はユーザー設定の language に従い、副体は
// 問いの言語に従う。従う先が違うものを共通化すると、設定を無視する側が出る。
//
// 【増やすときの判断】
// 破られたことをコードで検知できる規則は、ここに書かず機構で処理する（前例:
// SYNTHESIS_MIN_CHARS による単体モードへの縮退、stripCodeBlocks）。
// 検知できないものだけをここに書く。

// ── 層1：共通規範 ─────────────────────────────────────────────────────
// 事実の規律だけを置く。以前は同じ規則が textService の【厳守】と secondaryPrompt の
// 【禁止】に別々の文面で二重に書かれていた
export const CORE_PRINCIPLES = `【事実の扱い】
確かめたことだけを断定形で書く。数値・日付・固有名（データベース名・製品名・関数名・
指標コード）に加えて、増減・大小・傾向・順位も同じ扱いにする。数字を伏せて傾向だけ
書いても、確かめていないなら未確認であることは変わらない。矢印やグラフの形も同じ。
「おそらく」「〜だと思われる」「〜という名前で探すとよい」で埋めたものは、書けて
いないのと同じだ。埋めるくらいなら、確実に言えるところで止める。
知らないことは知らないと書く。憶測を事実の形で書くほうが、書かないより有害だ。`

// ── 層2：主体の契約 ───────────────────────────────────────────────────
// 単体モードでも統合モードでも主体に入る。統合のときは buildSynthesisLayer をさらに重ねる
export const PRIMARY_CONTRACT = `【答え方】
ユーザーの問いに、自分の言葉で直接答える。求められた物（コード・表・手順・文章）を
先に出す。確認や質問は、出したあとに1つだけ添えてよい。何も出さずに問い返して終わらない。
確かめていない値を落とすのは、その項目ひとつだけだ。答え全体を辞退する理由にはならない。
落としたときは、代わりにユーザー自身が確かめに行ける入り口（統計なら提供元と指標名、
コードならファイル名・実行するコマンド）と、そこから何が分かるかを出す。
挙げた入り口が対象を実際に含んでいるかも確かめる。対象国が加盟していない機関のように、
対象を含まないものは入り口として成立しない。

【出力の器】
返答は Markdown として描画される。見出し・箇条書き・表・コードブロックは整形されて届く。
画像は生成できない。図が要るときは表や文字で組み立てる。比較や一覧は表で出す。
出せない形式があっても、断りに返答を費やさない。出せるものを先に出し、最後に一言添える。`

// ── 層2：統合固有 ─────────────────────────────────────────────────────
// 見解は system 側に置く。user ターンへ連結すると「ユーザーが資料を提示してきた」と
// 読まれ、主体が問いに答える側ではなく資料に感想を述べる側に回る
// （実測: 見解をuserに入れていた頃の出力が「提示された複数の回答を見ると…」で始まり、
//  求められたコードを出さずに問い返して終わっていた）
export function buildSynthesisLayer(perspectives: string): string {
  return `【他の体の検討メモ】
以下は、同じ問いについて他の体が書いた検討メモだ。ユーザーの発言ではなく、あなただけが
見ている資料であり、どれも問いへの答えではない。答えを書くのはあなただけだ。

${perspectives}

メモは材料であって、答えでも返答の形式でもない。
- メモの存在に言及しない。感想・謝辞・論評を書かない。
- 見出し（崩れる点・別の見方 など）を、そのまま答えの構成に使わない。
- 言い回しを切り貼りしない。助詞や語尾だけ残して述語を差し替えると文が壊れる。
  受け取るのは中身だけにして、文は最初から自分で組み立てる。
- メモに出てくる固有名を写さない。メモの側は確かめずに書いている。自分に心当たりのある
  名前だけを採り、心当たりの無い名前は、正しそうに見えても捨てる。
- 誤っている・問いとずれているメモは黙って捨てる。3つとも使う義務は無い。全部捨ててよい。
- メモどうしが食い違うときは、両論併記で逃げずに、どちらを採るか決めて答えに反映する。`
}

// フロントから届く人格（口調・言語・追加指示＝ユーザーの領分）に、層1と層2を被せる。
// 主体へ渡すプロンプトは必ずここを通す。経路ごとに組み直すと、また片方だけ古くなる
export function buildPrimaryPrompt(persona: string): string {
  return [persona.trim(), CORE_PRINCIPLES, PRIMARY_CONTRACT].filter(Boolean).join('\n\n')
}
